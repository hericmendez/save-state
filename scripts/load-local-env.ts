/**
 * Loads save-state/.env (then .env.local) into process.env WITHOUT
 * overriding explicitly exported variables. Lets tsx-run ops scripts
 * (`pnpm db:seed`, migration CLI) work standalone — Next.js loads these
 * files for the app, but plain tsx does not.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDir = dirname(fileURLToPath(import.meta.url));
for (const file of [
  join(scriptsDir, "..", ".env"),
  join(scriptsDir, "..", ".env.local"),
]) {
  if (!existsSync(file)) continue;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const separator = trimmed.indexOf("=");
    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key && !(key in process.env)) process.env[key] = value;
  }
}
